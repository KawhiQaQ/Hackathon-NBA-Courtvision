def reviewed_frames(event_id,ids,duration,fps=24):
    paths=PATHS[event_id];rows=[]
    for i in range(math.ceil(duration*fps)+1):
        t=min(duration,i/fps);people=[]
        for pid,key,team in zip(ids,['actor','beneficiary','defense'],['light','light','dark']):
            points=paths[key];j=min(int(t),len(points)-1);a=points[j];b=points[min(j+1,len(points)-1)]
            if t>=paths.get('cut',float('inf')) or a is None or b is None:continue
            k=t-int(t);x,y,h=[u+(v-u)*k for u,v in zip(a,b)]
            people.append(dict(trackId=pid,x=(x-h*.24)/640,y=(y-h)/360,w=h*.48/640,h=h/360,
                team=team,confidence=.9,association=1,annotationSource='human-reviewed-identity-path-v2',ball='unknown'))
        rows.append({'time':t,'scene':0 if t<paths.get('cut',float('inf')) else 1,'people':people})
    return rows
